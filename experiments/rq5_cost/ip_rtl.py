"""RQ5 IP-count experiment for the open flow: the design of ip_net.tcl (Vivado block design) written
as RTL. Each unit holds six IP instances (counter, multiplier, adder, shift register, XOR reduction,
bit slice) with the same widths and connections as the Vivado units; units are grouped by ten into
groups and groups by ten into subsystems, and each group and subsystem reduces its members through a
concatenation and an XOR reduction, as in the block design. The seven IP modules are RTL files of
their own; the hierarchy is generated. The instance counts equal the Vivado IP-cell counts.

    python ip_rtl.py <units>...      build and record
    python ip_rtl.py time            time EGAudit on the recorded builds
"""
import shutil
import statistics
import sys
from pathlib import Path

HERE = Path(__file__).absolute().parent
sys.path.insert(0, str(HERE))
import ip_scaling as ips
from logic_scaling import c, time_check, utilization

BOARD = "zybo_open"
OUT = c.BUILD / "rq5_ip_rtl"

IP_MODULES = {
    "ip_counter.v": """module ip_counter #(parameter INC = 16'h0001) (input wire clk, output reg [15:0] q = 16'd0);
    always @(posedge clk) q <= q + INC;
endmodule
""",
    "ip_mult.v": """module ip_mult (input wire clk, input wire [15:0] a, input wire [15:0] b, output reg [31:0] p);
    always @(posedge clk) p <= a * b;
endmodule
""",
    "ip_addsub.v": """module ip_addsub (input wire clk, input wire [15:0] a, input wire [15:0] b, output reg [15:0] s);
    always @(posedge clk) s <= a + b;
endmodule
""",
    "ip_shift_ram.v": """module ip_shift_ram #(parameter DEPTH = 8) (input wire clk, input wire [15:0] d, output wire [15:0] q);
    reg [15:0] sr [0:DEPTH-1];
    integer k;
    always @(posedge clk) begin
        sr[0] <= d;
        for (k = 1; k < DEPTH; k = k + 1) sr[k] <= sr[k-1];
    end
    assign q = sr[DEPTH-1];
endmodule
""",
    "ip_reduce_xor.v": """module ip_reduce_xor #(parameter N = 16) (input wire [N-1:0] op, output wire res);
    assign res = ^op;
endmodule
""",
    "ip_slice.v": """module ip_slice (input wire [31:0] din, output wire [15:0] dout);
    assign dout = din[23:8];
endmodule
""",
    "ip_concat.v": """module ip_concat #(parameter N = 2) (input wire [N-1:0] din, output wire [N-1:0] dout);
    assign dout = din;
endmodule
""",
}


def hierarchy(units):
    """ipnet_wrapper (clk, q) with the same hierarchy and instance names as ip_net.tcl; returns text, IP count."""
    groups, subs, n_ip = {}, {}, 0
    for i in range(units):
        groups.setdefault((i // 100, (i // 10) % 10), []).append(i)
    mods = []
    for i in range(units):
        mods.append(f"""module unit_{i} (input wire clk, output wire b0);
    wire [15:0] q, lo, s, d;
    wire [31:0] p;
    ip_counter #(.INC(16'h{2 * i + 1:04X})) x_cnt (.clk(clk), .q(q));
    ip_mult x_mul (.clk(clk), .a(q), .b(q), .p(p));
    ip_slice x_lo (.din(p), .dout(lo));
    ip_addsub x_add (.clk(clk), .a(lo), .b(q), .s(s));
    ip_shift_ram #(.DEPTH({8 + i % 24})) x_srl (.clk(clk), .d(s), .q(d));
    ip_reduce_xor #(.N(16)) x_red (.op(d), .res(b0));
endmodule
""")
        n_ip += 6

    def reducer(name, members, inst_of):
        nonlocal n_ip
        n = len(members)
        body = "".join(f"    {inst_of(m)} u_{m} (.clk(clk), .b0(bits[{k}]));\n" for k, m in enumerate(members))
        n_ip += 2
        return f"""module {name} (input wire clk, output wire b0);
    wire [{n - 1}:0] bits, cat;
{body}    ip_concat #(.N({n})) x_cat (.din(bits), .dout(cat));
    ip_reduce_xor #(.N({n})) x_red (.op(cat), .res(b0));
endmodule
"""
    for (s, g), members in groups.items():
        mods.append(reducer(f"grp_{s}_{g}", members, lambda m: f"unit_{m}"))
        subs.setdefault(s, []).append(g)
    for s, gs in subs.items():
        mods.append(reducer(f"sub_{s}", gs, lambda g, s=s: f"grp_{s}_{g}"))
    if len(subs) == 1:
        top = f"""module ipnet_wrapper (input wire clk, output wire q);
    sub_{next(iter(subs))} u_sub (.clk(clk), .b0(q));
endmodule
"""
    else:
        top = reducer("ipnet_wrapper_r", list(subs), lambda s: f"sub_{s}").replace(
            "module ipnet_wrapper_r (input wire clk, output wire b0);",
            "module ipnet_wrapper (input wire clk, output wire q);\n    wire b0;\n    assign q = b0;")
    return "`timescale 1ns / 1ps\n// generated by rq5_cost/ip_rtl.py\n" + "\n".join(mods + [top]), n_ip


def make_design(units):
    src = ips.make_design(units)  # test design, board top with ipnet_wrapper, logic_fill with no lanes
    d = OUT / "designs" / src.name
    shutil.rmtree(d, ignore_errors=True)
    shutil.copytree(src, d)
    rtl = d / "rtl"
    for name, text in IP_MODULES.items():
        (rtl / name).write_text("`timescale 1ns / 1ps\n" + text)
    text, n_ip = hierarchy(units)
    (rtl / "ipnet.v").write_text(text)
    return d, n_ip


def build(units):
    d, n_ip = make_design(units)
    bdir = OUT / BOARD / f"u{units}_n0"
    rc, sec = c.build(d, BOARD, bdir)
    row = {"board": BOARD, "units": units, "ip_instances": n_ip, "vendor_build_s": round(sec, 1), "exit_code": rc}
    if rc == 0:
        row.update(zip(["logic_unit", "logic_used", "logic_available"], utilization(bdir, "openxc7")[:3]))
    ips.upsert(row)


def time_all():
    for row in ips.load():
        if row["board"] != BOARD or str(row["exit_code"]) != "0":
            continue
        bdir = OUT / BOARD / f"u{row['units']}_n0"
        ev, runs = time_check(bdir)
        files = [p for p in bdir.rglob("*") if p.is_file()]
        row.update(egaudit_ip=len(ev["ip"]), hier_levels=3, files=len(files), bytes=sum(p.stat().st_size for p in files),
                   egaudit_mean_s=round(statistics.mean(runs), 3), egaudit_sd_s=round(statistics.stdev(runs), 3))
        ips.upsert(row)


if __name__ == "__main__":
    if sys.argv[1] == "time":
        time_all()
    else:
        for u in map(int, sys.argv[1:]):
            build(u)
